"""US1 endpoint: GET /analytics/athletes/{athlete_id}/recommendation — AI coach."""

import logging
from typing import Any, Dict

from fastapi import APIRouter, Depends, HTTPException

from src.core.auth import get_current_user
from src.services.ai.ai_coach_service import (
    AICoachService,
    AIServiceUnavailableError,
    get_ai_coach_service,
)
from src.services.analytics.analytics_service import AnalyticsService, get_analytics_service

logger = logging.getLogger(__name__)

router = APIRouter()

AI_UNAVAILABLE_TEXT = "AI temporarily unavailable"


@router.get("/analytics/athletes/{athlete_id}/recommendation")
def get_athlete_recommendation(
    athlete_id: str,
    user: Dict[str, Any] = Depends(get_current_user),
    analytics: AnalyticsService = Depends(get_analytics_service),
    ai_coach: AICoachService = Depends(get_ai_coach_service),
) -> Dict[str, Any]:
    """Natural language practice focus generated by the AI coach (read-only)."""
    club_id = user.get("club_id")
    if not club_id:
        raise HTTPException(status_code=403, detail="Club access required")

    try:
        trends = analytics.get_athlete_trends(athlete_id, club_id=club_id)
        if not trends:
            raise HTTPException(status_code=404, detail="Athlete not found in your club")

        history = trends.get("history") or []
        scores = [h["figure_score"] for h in history if h.get("figure_score") is not None]
        radar = trends.get("radar") or []
        figure_averages = {r["figure"]: r["average"] for r in radar if r.get("average") is not None}

        try:
            recommendation = ai_coach.generate_recommendation(
                athlete_id=athlete_id,
                athlete_name=trends.get("name", ""),
                scores=scores,
                figure_averages=figure_averages,
            )
            return recommendation.model_dump(mode="json")
        except AIServiceUnavailableError:
            logger.warning("AI coach unavailable for athlete %s; returning fallback", athlete_id)
            return {
                "athlete_id": athlete_id,
                "recommendation_text": AI_UNAVAILABLE_TEXT,
                "generated_at": None,
                "weakest_figure": "",
            }
    except HTTPException:
        raise
    except Exception as exc:
        logger.exception("Recommendation failed for athlete %s", athlete_id)
        raise HTTPException(status_code=503, detail="Recommendation service unavailable") from exc
