import {
  Component,
  Input,
  OnChanges,
  SimpleChanges,
  inject,
  ChangeDetectorRef,
} from '@angular/core';

import { HttpClient } from '@angular/common/http';
import { firstValueFrom } from 'rxjs';

import { CardComponent } from '../../ui/card.component';
import { TypographyComponent } from '../../ui/typography.component';
import { LoadingSpinnerComponent } from '../../ui/loading-spinner.component';
import { environment } from '../../../../environments/environment';

interface RecommendationResponse {
  person_id: string;
  recommendation_text: string;
  generated_at: string | null;
  weakest_figure: string;
}

export const AI_UNAVAILABLE_TEXT = 'AI temporarily unavailable';

/**
 * AI recommendation widget: natural language practice focus generated by the
 * AI coach. Shows the generic "AI temporarily unavailable" error state when
 * the AI service cannot be reached (quickstart Scenario 2).
 */
@Component({
  selector: 'app-ai-recommendation-widget',
  standalone: true,
  imports: [CardComponent, TypographyComponent, LoadingSpinnerComponent],
  template: `
    <app-card title="AI Coach Focus" [subtitle]="subtitle()">
      @if (!personId) {
        <app-typography variant="body-medium" color="on-surface-variant">
          Select an athlete to view their AI practice focus.
        </app-typography>
      } @else if (loading) {
        <app-loading-spinner label="Loading recommendation"></app-loading-spinner>
      } @else {
        @if (unavailable) {
          <div class="ai-unavailable" role="status">
            <app-typography variant="body-large" color="error">
              {{ AI_UNAVAILABLE_TEXT }}
            </app-typography>
            <app-typography variant="body-small" color="on-surface-variant">
              The AI coaching service could not be reached. Please try again later.
            </app-typography>
          </div>
        } @else if (recommendation) {
          <blockquote class="recommendation">
            <app-typography variant="body-large" color="on-surface">
              {{ recommendation.recommendation_text }}
            </app-typography>
          </blockquote>
          @if (recommendation.weakest_figure) {
            <app-typography variant="label-large" color="primary">
              Weakest figure: {{ recommendation.weakest_figure }}
            </app-typography>
          }
        }
      }
    </app-card>
  `,
  styles: [
    `
      .recommendation {
        margin: 0 0 var(--md-sys-spacing-2);
        padding-left: var(--md-sys-spacing-3);
        border-left: 3px solid var(--md-sys-color-primary);
      }

      .ai-unavailable {
        display: flex;
        flex-direction: column;
        gap: var(--md-sys-spacing-1);
        padding: var(--md-sys-spacing-3);
        border: 1px solid var(--md-sys-color-error);
        border-radius: var(--md-sys-corner-medium);
        background: var(--md-sys-color-error-container);
        color: var(--md-sys-color-on-error-container);
      }
    `,
  ],
})
export class AIRecommendationWidgetComponent implements OnChanges {
  @Input() personId: string | null = null;
  @Input() athleteName: string | null = null;

  recommendation: RecommendationResponse | null = null;
  loading = false;
  unavailable = false;

  readonly AI_UNAVAILABLE_TEXT = AI_UNAVAILABLE_TEXT;

  private http = inject(HttpClient);
  private cdr = inject(ChangeDetectorRef);

  ngOnChanges(changes: SimpleChanges): void {
    if (changes['personId'] && this.personId) {
      void this.load();
    }
  }

  subtitle(): string {
    return this.athleteName ? `Practice focus for ${this.athleteName}` : 'Select an athlete';
  }

  private async load(): Promise<void> {
    if (!this.personId) {
      return;
    }
    this.loading = true;
    this.unavailable = false;
    this.recommendation = null;
    try {
      const res = await firstValueFrom(
        this.http.get<RecommendationResponse>(
          `${environment.apiUrl}/analytics/athletes/${this.personId}/recommendation`
        )
      );
      if (res.recommendation_text === AI_UNAVAILABLE_TEXT) {
        this.unavailable = true;
      } else {
        this.recommendation = res;
      }
    } catch {
      this.unavailable = true;
    } finally {
      this.loading = false;
      this.cdr.detectChanges();
    }
  }
}
