export class IconComponent {
  @Input() name: string = 'help';
  @Input() size: IconSize = 'medium';
  @Input() label = '';
  @Input() clickable = false;
  @Input() color: string = 'inherit';

  @HostBinding('class.icon') get isIcon() {
    return true;
  }
  @HostBinding('class.size-small') get isSmall() {
    return this.size === 'small';
  }
  @HostBinding('class.size-medium') get isMedium() {
    return this.size === 'medium';
  }
  @HostBinding('class.size-large') get isLarge() {
    return this.size === 'large';
  }
  @HostBinding('class.size-xlarge') get isXLarge() {
    return this.size === 'xlarge';
  }
  @HostBinding('class.clickable') get isClickable() {
    return this.clickable;
  }

  get iconClasses(): string {
    return `icon size-${this.size} ${this.clickable ? 'clickable' : ''}`;
  }

  get colorStyle(): string {
    if (this.color === 'inherit') return 'inherit';
    return `var(--md-sys-color-${this.color})`;
  }

  get sizeValue(): string {
    switch (this.size) {
      case 'small':
        return '16px';
      case 'medium':
        return '24px';
      case 'large':
        return '32px';
      case 'xlarge':
        return '48px';
      default:
        return '24px';
    }
  }

  protected readonly ICONS = ICONS;
}
